// Explicit build step: never mislabel page-open time as package build time.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.join(__dirname, '..', 'miniprogram');
require('./check-miniprogram-package.cjs').check();
const settingsBuild = path.join(root, 'pages/settings/utils/build.js');
const sessionSettingsBuild = path.join(root, 'pages/session-settings/utils/build.js');
const file = settingsBuild;
const version = require(file).BUILD_VERSION;
const hash = crypto.createHash('sha256');
function walk(relative) {
  const full = path.join(root, relative);
  if (relative === 'utils/build.js') return;
  if (relative === 'pages/settings/utils/build.js') return;
  if (relative === 'pages/session-settings/utils/build.js') return;
  if (fs.statSync(full).isDirectory()) {
    fs.readdirSync(full).sort().forEach(name => walk(relative + '/' + name));
  } else { hash.update(relative); hash.update('\0'); hash.update(fs.readFileSync(full)); }
}
['app.js', 'app.json', 'app.wxss', 'theme.json', 'pages', 'components', 'utils', 'assets', 'i18n'].filter(name => fs.existsSync(path.join(root, name))).forEach(walk);
const parts = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).formatToParts(new Date());
const date = Object.fromEntries(parts.map(part => [part.type, part.value]));
const build = { BUILD_VERSION: version, BUILD_TIME: date.year + '-' + date.month + '-' + date.day + ' ' + date.hour + ':' + date.minute, BUILD_ID: hash.digest('hex').slice(0, 8) };
const content = '// Generated by node scripts/stamp-build.cjs before compile/preview.\nmodule.exports = ' + JSON.stringify(build) + ';\n';
fs.mkdirSync(path.dirname(settingsBuild), { recursive: true });
fs.writeFileSync(settingsBuild, content);
fs.mkdirSync(path.dirname(sessionSettingsBuild), { recursive: true });
fs.writeFileSync(sessionSettingsBuild, content);
console.log('Build ' + build.BUILD_VERSION + ' · ' + build.BUILD_TIME + ' · ' + build.BUILD_ID);
