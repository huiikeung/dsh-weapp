function readBeforePackage() {
  const files = {
    js: path.join(beforeDir, 'ocean-background.js'),
    wxml: path.join(beforeDir, 'ocean-background.wxml'),
    wxss: path.join(beforeDir, 'ocean-background.wxss'),
    renderer: path.join(beforeDir, 'ocean-renderer.js')
  };
  const missing = Object.keys(files).filter((key) => !exists(files[key]));
  if (missing.length) throw new Error('missing BEFORE snapshot files: ' + missing.join(', '));
  console.log('BEFORE sources: preview/ocean/before-sources/ (frozen pre-split-layer snapshot)');
  return {
    js: readAbs(files.js),
    wxml: readAbs(files.wxml),
    wxss: readAbs(files.wxss),
    renderer: readAbs(files.renderer)
  };
}

function readAfterPackage() {
  const wxml = read('miniprogram/components/ocean-background/ocean-background.wxml');
  const wxss = read('miniprogram/components/ocean-background/ocean-background.wxss');
  const js = read('miniprogram/components/ocean-background/ocean-background.js');
  const renderer = read('miniprogram/utils/ocean-renderer.js');
  const assetDir = path.join(root, 'miniprogram/assets/ocean');
  const assets = fs.existsSync(assetDir)
    ? fs.readdirSync(assetDir).filter((name) => /\.(svg|png|webp)$/i.test(name))
    : [];
  const splitLayer = /ocean-grid|ocean-whale|ocean-dots|ocean-particle/.test(wxml);
  const enabled = splitLayer && assets.length > 0;
  const whales = {};
  if (enabled) {
    // The shipped wxml references one file per animated whale region
    // (ocean-whale-body / ocean-whale-tail), so read exactly those assets.
    const imageRe = /<image\b[^>]*class="([^"]*ocean-whale-[a-z]+)[^"]*"[^>]*src="\/assets\/ocean\/([^"]+)"[^>]*\/>/g;
    let match;
    while ((match = imageRe.exec(wxml))) {
      const className = match[1];
      const name = match[2];
      const rel = 'miniprogram/assets/ocean/' + name;
      if (!exists(rel)) continue;
      const mime = /\.svg$/i.test(name) ? 'image/svg+xml'
        : /\.png$/i.test(name) ? 'image/png' : 'image/webp';
      whales[className] = {
        path: rel,
        name: name,
        mime: mime,
        dataUrl: 'data:' + mime + ';base64,' + readBytes(rel).toString('base64')
      };
    }
  }
  const names = Object.keys(whales);
  const whale = names.length ? whales[names[0]] : null;
  return { enabled: enabled, wxml: wxml, wxss: wxss, js: js, renderer: renderer, whale: whale, whales: whales };
}

function fallbackWhaleDataUrl() {
  return 'data:image/png;base64,' + readBytes('miniprogram/assets/icons/bg-whale.png').toString('base64');
}

// Native reference: 1206x2622 (402x874pt @3x) cover-fitted to 390x844 @3x.
function buildNativeReference() {
  const target = path.join(outDir, 'native-reference.jpg');
  if (!exists(NATIVE_SOURCE)) {
    if (exists(target)) {
      console.warn('native source missing; keeping existing', path.relative(root, target));
      return target;
    }
    throw new Error('native reference source missing: ' + NATIVE_SOURCE);
  }
  const py = [
    'from PIL import Image',
    'im = Image.open(' + JSON.stringify(NATIVE_SOURCE) + ').convert("RGB")',
    'tw, th = ' + WIDTH * DPR + ', ' + HEIGHT * DPR,
    'scale = max(tw / im.width, th / im.height)',
    'w, h = round(im.width * scale), round(im.height * scale)',
    'im = im.resize((w, h), Image.LANCZOS)',
    'left, top = (w - tw) // 2, (h - th) // 2',
    'im = im.crop((left, top, left + tw, top + th))',
    'im.save(' + JSON.stringify(target) + ', "JPEG", quality=95, subsampling=0, optimize=True)',
    'print("native reference", im.size, ' + JSON.stringify(path.relative(root, target)) + ')'
  ].join('\n');
  try {
    process.stdout.write(execFileSync('python3', ['-c', py], { encoding: 'utf8' }));
    return target;
  } catch (error) {
    console.warn('PIL resize failed, trying sips:', error.message.split('\n')[0]);
    const temp = path.join(outDir, 'native-reference.tmp.png');
    execFileSync('sips', ['--resampleWidth', String(WIDTH * DPR), NATIVE_SOURCE, '--out', temp], { stdio: 'ignore' });
    execFileSync('sips', ['-c', String(HEIGHT * DPR), String(WIDTH * DPR), temp], { stdio: 'ignore' });
    execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '95', temp, '--out', target], { stdio: 'ignore' });
    fs.rmSync(temp, { force: true });
    return target;
  }
}

// Parse the shipped wxml into the static layer stack: transparent <block>s are
// flattened, duplicate conditional branches (buffered frames) keep the first
// image, and image sources are mapped to the generated frame / whale assets.
function parseWxmlLayers(wxml) {
  var CLASS_RE = /class="([^"]*)"/;
  var tokens = wxml.match(/<\/?[a-zA-Z-]+\b[^>]*?>/g) || [];
  var stack = [{ tag: 'root', className: '', children: [] }];
  for (var i = 0; i < tokens.length; i++) {
    var token = tokens[i];
    var closing = token.charAt(1) === '/';
    var nameMatch = token.match(/^<\/?([a-zA-Z-]+)/);
    if (!nameMatch) continue;
    var tag = nameMatch[1];
    if (closing) {
      if (stack.length > 1) stack.pop();
      continue;
    }
    var classMatch = token.match(CLASS_RE);
    var staticTokens = classMatch ? classMatch[1].split(/\s+/).filter(function (part) {
      return part && part.indexOf('{{') < 0 && part.indexOf('}}') < 0;
    }) : [];
    var node = { tag: tag, className: staticTokens[0] || '', children: [] };
    var srcMatch = token.match(/src="([^"]*)"/);
    if (srcMatch) node.src = srcMatch[1];
    stack[stack.length - 1].children.push(node);
    if (token.indexOf('/>') !== 0 && !/\/>$/.test(token)) stack.push(node);
  }
  var root = stack[0].children.filter(function (node) { return node.className === 'ocean-background' || /ocean-background/.test(node.className); })[0];
  if (!root) return null;
  var mapping = {
    'ocean-frame': '$FLUID_FRAME',
    'ocean-whale-body': '$WHALE_BODY',
    'ocean-whale-tail': '$WHALE_TAIL'
  };
  var seen = {};
  function flatten(children) {
    var out = [];
    children.forEach(function (node) {
      if (node.tag === 'block') { out = out.concat(flatten(node.children)); return; }
      var layer = { tag: node.tag === 'image' ? 'img' : node.tag === 'view' ? 'div' : node.tag, className: node.className };
      if (node.tag === 'image' || node.tag === 'img') {
        if (mapping[node.className]) layer.src = mapping[node.className];
        else if (/whale/i.test(node.src || '')) layer.src = '$WHALE';
      }
      if (node.children && node.children.length) layer.children = flatten(node.children);
      var key = layer.tag + '|' + layer.className + '|' + (layer.src || '');
      if (seen[key]) return;
      seen[key] = true;
      out.push(layer);
    });
    return out;
  }
  var layers = flatten(root.children);
  var classes = layers.map(function (layer) { return layer.className; });
  var expected = ['ocean-base', 'ocean-fluid', 'ocean-grain', 'ocean-grid', 'ocean-whale', 'ocean-depth', 'ocean-settle'];
  var valid = expected.every(function (name) { return classes.indexOf(name) >= 0; });
  return valid ? layers : null;
}

// Fallback AFTER layer stack if wxml parsing ever fails.
function afterLayerStack() {
  return [
    { tag: 'div', className: 'ocean-base' },
    {
      tag: 'div', className: 'ocean-fluid', children: [
        { tag: 'img', className: 'ocean-frame', src: '$FLUID_FRAME' }
      ]
    },
    { tag: 'div', className: 'ocean-grain' },
    { tag: 'div', className: 'ocean-grid' },
    {
      tag: 'div', className: 'ocean-whale', children: [
        { tag: 'img', className: 'ocean-whale-body', src: '$WHALE_BODY' },
        { tag: 'img', className: 'ocean-whale-tail', src: '$WHALE_TAIL' }
      ]
    },
    { tag: 'div', className: 'ocean-depth' },
    { tag: 'div', className: 'ocean-settle' }
  ];
}

function main() {
  fs.mkdirSync(outDir, { recursive: true });
  const before = readBeforePackage();
  const after = readAfterPackage();

  const beforeConfig = componentConfig(before.js, 0.7, 0.68);
  const afterConfig = componentConfig(after.js, 0.7, 0.72);
  const parsedLayers = after.enabled ? parseWxmlLayers(after.wxml) : null;
  const layers = parsedLayers || afterLayerStack();
  const config = {
    width: WIDTH,
    height: HEIGHT,
    dpr: DPR,
    before: {
      ratio: beforeConfig.ratio,
      quality: beforeConfig.quality,
      time: TIME,
      ratioExpression: beforeConfig.ratioExpression
    },
    after: after.enabled ? {
      ratio: afterConfig.ratio,
      quality: afterConfig.quality,
      time: TIME,
      ratioExpression: afterConfig.ratioExpression,
      crossfadeMs: crossfadeMs(after.wxss),
      whalePath: after.whale ? after.whale.path : null,
      whale: after.whale ? after.whale.dataUrl : null,
      whales: Object.keys(after.whales || {}).reduce(function (out, key) { out[key] = after.whales[key].dataUrl; return out; }, {}),
      layers: layers
    } : null,
    freeze: { grainPosition: '7px -17px' },
    assets: { whaleFallback: fallbackWhaleDataUrl() },
    benchmark: {
      ratios: [0.4, 0.5, 0.62, 0.7, 0.72, 0.75, 1.0],
      qualities: [0.62, 0.70, 0.72, 0.78],
      frames: 30
    }
  };

  fs.writeFileSync(path.join(outDir, 'component-before.css'),
    '/* Generated from preview/ocean/before-sources/ocean-background.wxss by scripts/build-ocean-preview.cjs. Do not edit. */\n' +
    scopeCss(convertWxss(before.wxss), '.ocean-before'));
  fs.writeFileSync(path.join(outDir, 'component-after.css'),
    '/* Generated from miniprogram/components/ocean-background/ocean-background.wxss by scripts/build-ocean-preview.cjs. Do not edit. */\n' +
    scopeCss(convertWxss(after.wxss), '.ocean-after'));
  fs.writeFileSync(path.join(outDir, 'ocean-module-before.js'), browserOceanModule('OCEAN_MODULE_BEFORE', before.renderer, true));
  fs.writeFileSync(path.join(outDir, 'ocean-module-after.js'), browserOceanModule('OCEAN_MODULE_AFTER', after.renderer, /ocean-particles/.test(after.renderer)));
  fs.writeFileSync(path.join(outDir, 'config.js'), 'window.OCEAN_PREVIEW = ' + JSON.stringify(config, null, 2) + ';\n');
  const nativeReference = buildNativeReference();

  console.log('wrote preview/ocean/{component-before,component-after}.css, ocean-module-{before,after}.js, config.js');
  console.log('BEFORE: ratio ' + config.before.ratio.toFixed(4) + ', q' + config.before.quality + ', formula ' + config.before.ratioExpression);
  console.log('AFTER : ' + (config.after
    ? 'ratio ' + config.after.ratio.toFixed(4) + ', q' + config.after.quality + ', crossfade ' + config.after.crossfadeMs + 'ms, whales ' + Object.keys(config.after.whales).length + ' (' + config.after.whalePath + '...)' +
      ', layers ' + (parsedLayers ? 'parsed from wxml' : 'fallback list') + ' (' + layers.length + ')'
    : 'not detected (split-layer wxml/asset missing); rerun after the AFTER code lands'));
  console.log('native reference: ' + path.relative(root, nativeReference));
}

main();
