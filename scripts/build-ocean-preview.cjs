// WXSS -> CSS. Data-URI payloads are protected first: base64 routinely contains
// "vw"/"vh"/"rpx"-like runs and must never be rewritten.
function convertWxss(source) {
  const payloads = [];
  let text = source.replace(/url\("(data:[^"]+)"\)/g, (match, uri) => {
    payloads.push(uri);
    return 'url("__OCEAN_DATA_URL_' + (payloads.length - 1) + '__")';
  });
  text = text
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(-?\d+(?:\.\d+)?)rpx/g, (_, v) => round(parseFloat(v) * RPX) + 'px')
    .replace(/(-?\d+(?:\.\d+)?)vw/g, (_, v) => round(parseFloat(v) * WIDTH / 100) + 'px')
    .replace(/(-?\d+(?:\.\d+)?)vh/g, (_, v) => round(parseFloat(v) * HEIGHT / 100) + 'px')
    .replace(/env\(safe-area-inset-[a-z]+\)/g, '0px')
    .replace(/:host\b/g, '.ocean-root');
  return text.replace(/url\("__OCEAN_DATA_URL_(\d+)__"\)/g, (_, index) => 'url("' + payloads[Number(index)] + '")');
}

// Prefix every selector with a stage scope so the BEFORE and AFTER stylesheets
// can coexist on one page. @keyframes stay global (shared names are identical).
function scopeCss(css, scope) {
  let out = '';
  let index = 0;
  while (index < css.length) {
    const brace = css.indexOf('{', index);
    if (brace < 0) break;
    const prelude = css.slice(index, brace).trim();
    let depth = 0;
    let cursor = brace;
    for (; cursor < css.length; cursor++) {
      if (css[cursor] === '{') depth++;
      else if (css[cursor] === '}') { depth--; if (depth === 0) break; }
    }
    const body = css.slice(brace + 1, cursor);
    if (/^@media\b/.test(prelude)) {
      out += prelude + ' {\n' + scopeCss(body, scope) + '}\n';
    } else if (/^@keyframes\b/.test(prelude)) {
      out += prelude + ' {' + body + '}\n';
    } else {
      const selectors = prelude.split(',').map((part) => part.trim()).filter(Boolean)
        .map((part) => scope + ' ' + part);
      out += selectors.join(',\n') + ' {' + body + '}\n';
    }
    index = cursor + 1;
  }
  return out;
}

