function colorKey(color) {
  const rgb = rgbOf(color);
  return '#' + rgb.map(channel => Math.round(channel).toString(16).padStart(2, '0')).join('');
}

function render() {
  const blocks = ['/* Generated by scripts/generate-status-tail-animation.cjs. */'];
  OPTIONS.forEach(item => {
    ['light', 'dark'].forEach(mode => {
      const colors = item[mode];
      const frames = colors.map((color, index) => {
        const key = colorKey(color);
        const filter = FILTERS[key];
        if (!filter) throw new Error('Missing whale filter for ' + key);
        const percent = (index / colors.length * 100).toFixed(4).replace(/\.0+$/, '').replace(/(\.\d*?)0+$/, '$1');
        return percent + '%{filter:' + filter + '}';
      });
      frames.push('100%{filter:' + FILTERS[colorKey(colors[0])] + '}');
      const name = 'statusTail' + item.id[0].toUpperCase() + item.id.slice(1) + mode[0].toUpperCase() + mode.slice(1);
      blocks.push('.status-tail-' + item.id + '.status-tail-' + mode + '{animation-name:' + name + '}\n@keyframes ' + name + '{' + frames.join('') + '}');
    });
  });
  return blocks.join('\n') + '\n';
}

if (require.main === module) {
  const output = path.join(__dirname, '../miniprogram/styles/status-tail-animation.wxss');
  fs.writeFileSync(output, render());
}

module.exports = { render };
