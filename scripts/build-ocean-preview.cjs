// Rebuilds the generated inputs of preview/ocean/ from the REAL mini program
// sources so the Chrome preview cannot drift from what ships.
//
//   node scripts/build-ocean-preview.cjs
//
// BEFORE sources are frozen under preview/ocean/before-sources/ (snapshot of the
// pre-split-layer working tree, taken before the AFTER rewrite landed, so the
// "rough" baseline stays reproducible). AFTER sources are read live:
//   miniprogram/components/ocean-background/ocean-background.{js,wxml,wxss}
//   miniprogram/utils/ocean-renderer.js, ocean-particles.js
//   miniprogram/assets/ocean/whale-body.svg + whale-tail.svg
//
// Generated (do not hand edit):
//   preview/ocean/component-before.css / component-after.css  (wxss -> px, scoped per stage)
//   preview/ocean/ocean-module-before.js / ocean-module-after.js (CommonJS shim around renderer)
//   preview/ocean/config.js       (render ratio / JPEG quality / layer config)
//   preview/ocean/native-reference.jpg (dsh-mobile reference cropped to 390x844 @3x)
//
// Hand written, mirrored from the shipped wxml: index.html, page.js, shoot.cjs.
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'preview/ocean');
const beforeDir = path.join(outDir, 'before-sources');
const WIDTH = 390;
const HEIGHT = 844;
const DPR = 3;
const RPX = WIDTH / 750; // 750rpx = one screen width
const TIME = 8; // seconds of fluid animation for a representative steady frame
const NATIVE_SOURCE = '/tmp/dsh-mobile-ref/Design/harness-background-simulator-v2.png';

const readAbs = (file) => fs.readFileSync(file, 'utf8');
const read = (rel) => readAbs(path.join(root, rel));
const readBytes = (rel) => fs.readFileSync(path.join(root, rel));
const exists = (file) => fs.existsSync(file);
const round = (value) => String(Math.round(parseFloat(value) * 100) / 100);

