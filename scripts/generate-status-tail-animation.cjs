const fs = require('node:fs');
const path = require('node:path');
const { OPTIONS, rgbOf } = require('../miniprogram/pages/session/utils/status-appearance');

// 状态条鲸尾的着色方式。
//
// 历史做法：一张纯黑 + alpha 的鲸尾图，靠 CSS filter 链（invert/sepia/saturate/hue-rotate/
// brightness/contrast）染成目标色，再用 @keyframes 在相邻色点之间插值。两个问题绕不过去：
//   1) CSS 在两个关键帧之间是逐个 filter 参数线性插值，不是 RGB 插值，色点之间会串色；
//   2) 各端渲染 filter 的结果并不一致——Chromium（开发者工具 / 安卓 / 鸿蒙）与 WebKit
//      （iOS 微信）做这些色彩矩阵时的色彩空间和裁剪方式不同，同一个 filter 在 iOS 上明显更亮
//      更饱和，于是出现「文字深绿、鲸尾薄荷绿」。这属于渲染引擎差异，调关键帧数值永远修不好。
//
// 所以这里完全不用 filter：
//   - 鲸尾轮廓作 mask（内联 data URI，WXSS 不涉及路径解析；首页 ocean-background 已在用
//     -webkit-mask-image，iOS 可用）；
//   - 颜色用 background-color 关键帧，色点直接取自文字渐变的那些颜色、位置一一对应。
// 遮罩原理：背景色铺满元素，只有 PNG 不透明的部分透出来，形态与原鲸尾图完全一致。
// 这样鲸尾与文字用的是同一套 sRGB 数值，任何渲染引擎都会得到同一个颜色。

const WHALE = 'miniprogram/assets/icons/dsh-running-whale.png';

function maskDataUri() {
  return 'data:image/png;base64,' + fs.readFileSync(path.join(__dirname, '..', WHALE)).toString('base64');
}

/** 文字渐变在整段文字左缘的颜色序列：色点 i 出现在进度 i/n，末尾回到首色。 */
function keyframeStops(colors) {
  const stops = colors.map((color, index) => ({
    percent: (index / colors.length) * 100,
    color: cssColor(color)
  }));
  stops.push({ percent: 100, color: cssColor(colors[0]) });
  return stops;
}

function cssColor(color) {
  return 'rgb(' + rgbOf(color).map(value => Math.round(value)).join(',') + ')';
}

function formatPercent(value) {
  const text = value.toFixed(4).replace(/\.0+$/, '').replace(/(\.\d*?)0+$/, '$1');
  return (text === '' ? '0' : text) + '%';
}

function renderCss() {
  const uri = maskDataUri();
  const blocks = [
    '/* Generated by scripts/generate-status-tail-animation.cjs. */',
    '.status-tail-ink{width:28rpx;height:28rpx;display:block;flex-shrink:0;'
      + 'background-color:transparent;-webkit-mask-image:url("' + uri + '");mask-image:url("' + uri + '");'
      + '-webkit-mask-size:100% 100%;mask-size:100% 100%;'
      + '-webkit-mask-repeat:no-repeat;mask-repeat:no-repeat;'
      + '-webkit-mask-position:center;mask-position:center;}'
  ];
  OPTIONS.forEach(item => {
    ['light', 'dark'].forEach(mode => {
      const colors = item[mode];
      const name = 'statusTail' + item.id[0].toUpperCase() + item.id.slice(1) + mode[0].toUpperCase() + mode.slice(1);
      const selector = '.status-tail-ink.status-tail-' + item.id + '.status-tail-' + mode;
      blocks.push(selector + '{animation-name:' + name + ';background-color:' + cssColor(colors[0]) + '}');
      blocks.push('@keyframes ' + name + '{'
        + keyframeStops(colors).map(stop => formatPercent(stop.percent) + '{background-color:' + stop.color + '}').join('')
        + '}');
    });
  });
  return blocks.join('\n') + '\n';
}

/** 校验用：每个样式/主题的关键帧色点与顺序。 */
function expectations() {
  return OPTIONS.map(item => ({
    id: item.id,
    light: keyframeStops(item.light).map(stop => ({ percent: +stop.percent.toFixed(4), color: stop.color })),
    dark: keyframeStops(item.dark).map(stop => ({ percent: +stop.percent.toFixed(4), color: stop.color }))
  }));
}

/** 文字渐变左缘在进度 t 的颜色。 */
function textColorAt(colors, t) {
  const list = colors.map(color => rgbOf(color));
  const count = list.length;
  const position = (((t % 1) + 1) % 1) * count;
  const index = Math.floor(position) % count;
  const mix = position - Math.floor(position);
  const from = list[index];
  const to = list[(index + 1) % count];
  return [0, 1, 2].map(channel => from[channel] + (to[channel] - from[channel]) * mix);
}

/**
 * 校验用：按 CSS 规则把关键帧线性插值还原成颜色，与文字渐变逐点比对。
 * 这条路径不含 filter 数学，误差应恒为 0，测试用它守住「鲸尾与文字同色」的约束。
 */
function measure(samples) {
  const count = samples || 120;
  let worst = 0;
  let detail = null;
  const rows = [];
  OPTIONS.forEach(item => {
    ['light', 'dark'].forEach(mode => {
      const stops = keyframeStops(item[mode]).map(stop => ({ t: stop.percent / 100, rgb: rgbOf(stop.color) }));
      let worstHere = 0;
      for (let index = 0; index <= count; index += 1) {
        const t = index / count;
        let right = stops.findIndex(stop => stop.t >= t - 1e-9);
        if (right <= 0) right = 1;
        const left = stops[right - 1];
        const span = stops[right].t - left.t || 1;
        const mix = (t - left.t) / span;
        const rendered = left.rgb.map((value, channel) => value + (stops[right].rgb[channel] - value) * mix);
        const target = textColorAt(item[mode], t);
        const error = Math.max(...rendered.map((value, channel) => Math.abs(value - target[channel])));
        if (error > worstHere) worstHere = error;
        if (error > worst) { worst = error; detail = { style: item.id, mode, t: +t.toFixed(4), error: +error.toFixed(2) }; }
      }
      rows.push({ style: item.id, mode, maxError: +worstHere.toFixed(2), stops: stops.length });
    });
  });
  return { worst, detail, rows, stops: rows.reduce((sum, row) => sum + row.stops, 0) };
}

if (require.main === module) {
  const output = path.join(__dirname, '../miniprogram/styles/status-tail-animation.wxss');
  fs.writeFileSync(output, renderCss());
  const result = measure();
  console.log(JSON.stringify({ bytes: fs.statSync(output).size, worstChannelError: +result.worst.toFixed(2), stops: result.stops }));
}

module.exports = { render: renderCss, measure, measureWorstError: measure, textColorAt, keyframeStops, maskDataUri };
