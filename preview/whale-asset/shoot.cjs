// Whale-dot layer verification shots.
// Usage: node preview/whale-asset/shoot.cjs
//
// Renders preview/whale-asset/index.html (the shipping ocean shader as the
// background + the real whale-dot SVG at the component's CSS geometry) at
// 390x844 @3x through preview/whale-asset/cdp-shot.cjs -- headless Chrome's
// CLI enforces a ~500 CSS px minimum window, which would break 115vw geometry.
// Then builds native-vs-asset comparison sheets against
// /tmp/dsh-mobile-ref/Design/harness-background-simulator-v2.png (402x874 @3x).
//
// Outputs (all under preview/whale-asset/):
//   layer-390x844.png              shipping stack (round dots), 115vw @3x
//   layer-square-390x844.png       square-dot variant, same stack
//   layer-402x874.png              shipping stack at the reference's 402x874 pt
//   layer-square-402x874.png       square-dot variant at 402x874 pt
//   whale-only-390x844.png         whale over a plain navy gradient
//   asset-390x844.png              round dots only, no screen blending
//   asset-square-390x844.png       square dots only
//   native-vs-asset-full.png       native screenshot | shipping stack
//   dots-native-square-round.png   3 columns x 2 regions, 2x device px crops:
//                                  native reference | butt-capped square | round
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const dir = __dirname;
const repo = path.resolve(dir, '../..');
const rendererSource = path.join(repo, 'miniprogram/utils/ocean-renderer.js');
const cdpShot = path.join(dir, 'cdp-shot.cjs');
const REFERENCE = '/tmp/dsh-mobile-ref/Design/harness-background-simulator-v2.png';
const SHIPPED = '../../miniprogram/assets/ocean/whale-dots.svg';
const SQUARE = 'whale-dots-square.svg';

// The preview must run the shader that actually ships today: regenerate
// shader.js from miniprogram/utils/ocean-renderer.js on every shot.
function writeShader() {
  const source = fs.readFileSync(rendererSource, 'utf8');
  const match = source.match(/const FRAGMENT = `([\s\S]*?)`;/);
  if (!match) throw new Error('FRAGMENT shader not found in miniprogram/utils/ocean-renderer.js');
  fs.writeFileSync(path.join(dir, 'shader.js'),
    '// Generated by preview/whale-asset/shoot.cjs from miniprogram/utils/ocean-renderer.js.\n' +
    'window.OCEAN_FRAGMENT = ' + JSON.stringify(match[1]) + ';\n');
}

function capture(name, { width, height, dpr, url, wait }) {
  const out = path.join(dir, name);
  execFileSync(process.execPath, [cdpShot, url, out, String(width), String(height), String(dpr), String(wait || 900)], { stdio: 'ignore' });
  console.log('wrote ' + name + ' (' + width + 'x' + height + ' CSS @' + dpr + 'x, ' + fs.statSync(out).size + ' bytes)');
}

writeShader();

const page = query => 'file://' + path.join(dir, 'index.html') + (query ? '?' + query : '');
const urlOf = file => 'file://' + (path.isAbsolute(file) ? file : path.join(dir, file));
capture('layer-390x844.png', { width: 390, height: 844, dpr: 3, url: page('') });
capture('layer-square-390x844.png', { width: 390, height: 844, dpr: 3, url: page('asset=' + SQUARE) });
// 402x874 is exactly the native reference screenshot's geometry, so the two
// PNGs are pixel-aligned for the A/B sheets.
capture('layer-402x874.png', { width: 402, height: 874, dpr: 3, url: page('') });
capture('layer-square-402x874.png', { width: 402, height: 874, dpr: 3, url: page('asset=' + SQUARE) });
capture('whale-only-390x844.png', { width: 390, height: 844, dpr: 3, url: page('mode=whale') });
capture('asset-390x844.png', { width: 390, height: 844, dpr: 3, url: page('mode=asset') });
capture('asset-square-390x844.png', { width: 390, height: 844, dpr: 3, url: page('mode=asset&asset=' + SQUARE) });

// ---- comparison sheets ----------------------------------------------------
if (!fs.existsSync(REFERENCE)) {
  console.log('reference screenshot missing at ' + REFERENCE + '; skipped comparison sheets');
  process.exit(0);
}

const sheet = (body, width) => '<!doctype html><html><head><meta charset="utf-8"><style>' +
  'html,body{margin:0;background:#050b15;font:12px/1.4 -apple-system,system-ui,sans-serif;color:#9fb2cc}' +
  '.row{display:flex;gap:12px;padding:12px}.panel{position:relative;margin:0}.panel img{display:block;border-radius:8px}' +
  'figcaption{padding:6px 2px 0;letter-spacing:.02em}.crop{border-radius:8px}' +
  '</style></head><body style="width:' + width + 'px">' + body + '</body></html>';

function writeSheet(name, html, width, height) {
  const file = path.join(dir, name + '.html');
  fs.writeFileSync(file, html);
  capture(name + '.png', { width, height, dpr: 1, url: 'file://' + file, wait: 2500 });
}

// Full screen: native reference next to the shipping stack at 402x874 @3x.
writeSheet('native-vs-asset-full', sheet(
  '<div class="row">' +
  '<figure class="panel"><img src="' + urlOf(REFERENCE) + '" width="300" height="652"><figcaption>native dsh-mobile reference (402x874 @3x)</figcaption></figure>' +
  '<figure class="panel"><img src="' + urlOf('layer-402x874.png') + '" width="300" height="652"><figcaption>weapp: shader background + whale-dots.svg (DPR 3)</figcaption></figure>' +
  '</div>', 640), 640, 700);

// 1:1 device-pixel crops, magnified 2x with nearest-neighbour, so dot shape and
// lattice alignment are directly comparable. All three sources are 1206x2622.
function cropPanel(file, crop, zoom, caption) {
  const style = 'width:' + (crop.w * zoom) + 'px;height:' + (crop.h * zoom) + 'px;' +
    "background-image:url('" + urlOf(file) + "');" +
    'background-repeat:no-repeat;image-rendering:pixelated;' +
    'background-size:' + (1206 * zoom) + 'px ' + (2622 * zoom) + 'px;' +
    'background-position:' + (-crop.x * zoom) + 'px ' + (-crop.y * zoom) + 'px;';
  return '<figure class="panel"><div class="crop" style="' + style + '"></div>' +
    '<figcaption>' + caption + '</figcaption></figure>';
}
const REGIONS = [
  { label: 'head + body', crop: { x: 170, y: 420, w: 260, h: 200 } },
  { label: 'tail', crop: { x: 780, y: 390, w: 260, h: 200 } }
];
const zoom = 2;
const columns = [
  { file: REFERENCE, caption: 'native reference' },
  { file: 'layer-square-402x874.png', caption: 'butt-capped square dots' },
  { file: 'layer-402x874.png', caption: 'round dots (shipped)' }
];
const rows = REGIONS.map(region =>
  '<div class="row">' + columns.map(column =>
    cropPanel(column.file, region.crop, zoom, column.caption + ' - ' + region.label)).join('') + '</div>').join('');
const sheetWidth = 3 * (REGIONS[0].crop.w * zoom) + 4 * 12;
const sheetHeight = REGIONS.length * (REGIONS[0].crop.h * zoom + 24) + 24;
writeSheet('dots-native-square-round', sheet(rows, sheetWidth), sheetWidth, sheetHeight);
