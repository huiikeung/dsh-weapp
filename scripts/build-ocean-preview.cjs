// Embed the shipped shader module (CommonJS) as a browser global.
function browserOceanModule(globalName, rendererSource, useParticles) {
  const lines = [
    '// Generated by scripts/build-ocean-preview.cjs from miniprogram/utils/ocean-renderer.js.',
    '// Do not edit.',
    'window.' + globalName + ' = (function () {',
    '  var module = { exports: {} };',
    '  var require = function (name) {',
    '    if (name === "./ocean-particles") return particlesModule;',
    '    throw new Error("preview: unexpected require(" + name + ")");',
    '  };'
  ];
  if (useParticles) {
    lines.splice(3, 0,
      '  var particlesModule = (function () { var module = { exports: {} };',
      read('miniprogram/utils/ocean-particles.js'),
      '    return module.exports; })();');
  } else {
    lines.splice(3, 0, '  var particlesModule = null;');
  }
  lines.push(rendererSource, '  return module.exports;', '})();');
  return lines.join('\n');
}

// Read function declarations / integer constants so expressions that reference
// helpers (e.g. fluidPixelRatio(field.width, field.height)) can be evaluated.
function extractFunction(source, name) {
  const start = source.indexOf('function ' + name);
  if (start < 0) return null;
  const brace = source.indexOf('{', start);
  if (brace < 0) return null;
  let depth = 0;
  for (let cursor = brace; cursor < source.length; cursor++) {
    if (source[cursor] === '{') depth++;
    else if (source[cursor] === '}') { depth--; if (!depth) return source.slice(start, cursor + 1); }
  }
  return null;
}

function extractConstants(source) {
  const out = [];
  const pattern = /const\s+([A-Z][A-Z0-9_]*)\s*=\s*(-?[\d.]+)\s*;/g;
  let match;
  while ((match = pattern.exec(source))) out.push('var ' + match[1] + ' = ' + match[2] + ';');
  return out;
}

function evaluateRatio(source, expression) {
  if (!expression) return null;
  const candidates = [
    ['info', 'field', 'return (' + expression + ');'],
    ['info', 'field', extractConstants(source).join('\n') + '\nreturn (' + expression + ');'],
    ['info', 'field', extractConstants(source).join('\n') + '\n' + (extractFunction(source, 'fluidPixelRatio') || '') + '\nreturn (' + expression + ');']
  ];
  for (const args of candidates) {
    try {
      const value = Number(new Function(args[0], args[1], args[2])({ pixelRatio: DPR }, { width: WIDTH, height: HEIGHT }));
      if (isFinite(value) && value > 0) return value;
    } catch (error) { /* try the next shape */ }
  }
  return null;
}

function findQuality(source) {
  const literal = source.match(/toDataURL\('image\/jpeg',\s*([\d.]+)\)/g);
  if (literal && literal.length) {
    const last = literal[literal.length - 1].match(/([\d.]+)\)/);
    if (last) return Number(last[1]);
  }
  const constant = source.match(/FLUID_JPEG_QUALITY\s*=\s*([\d.]+)/);
  if (constant) return Number(constant[1]);
  return null;
}

function componentConfig(source, fallbackRatio, fallbackQuality) {
  const ratioMatch = source.match(/_pixelRatio\s*=\s*([^;]+);/);
  const ratio = evaluateRatio(source, ratioMatch ? ratioMatch[1].trim() : null) || fallbackRatio;
  const quality = findQuality(source) || fallbackQuality;
  return {
    ratio: ratio,
    quality: quality,
    ratioExpression: ratioMatch ? ratioMatch[1].trim() : null
  };
}

function crossfadeMs(wxss) {
  const block = wxss.match(/\.ocean-fluid[^{]*\{[^}]*transition[^}]*\}/);
  if (block) {
    const ms = block[0].match(/(\d+(?:\.\d+)?)ms/);
    if (ms) return Number(ms[1]);
    const seconds = block[0].match(/transition[^;]*?(\d+(?:\.\d+)?)s/);
    if (seconds) return Number(seconds[1]) * 1000;
  }
  return 520;
}

